// Builds res/values-<lang>/ translations from tools/i18n/<lang>.js and checks them against English.
// Usage: node tools/i18n/build.js            (all languages)
const fs = require('fs');
const path = require('path');

const RES = path.join(__dirname, '../../app/src/main/res');
const BASE_FILES = ['strings.xml', 'rumors.xml', 'stats_missions.xml'];
// Strings that are the same in every language and fall back to English
const SKIP = new Set([
  'app_name', 'toy_name', 'home_onboarding_step_format', 'home_progress_percentage', 'home_header_title',
  'settings_weather_provider_openweathermap', 'settings_weather_help_url', 'sleep_bedtime_range',
  'pokedex_progress_subtitle', 'pokedex_entry_number', 'inventory_item_quantity', 'stats_duration',
  'pokedex_region_kanto', 'pokedex_region_johto', 'pokedex_region_hoenn', 'pokedex_region_sinnoh',
  'rumors_unknown_name', 'components_exp_chip', 'caught_screen_filter_shiny'
]);

const unescape = v => v.replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\\?/g, '?').replace(/&amp;/g, '&').replace(/&lt;/g, '<');
const escape = v => v.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/\\/g, '\\\\').replace(/'/g, "\\'")
  .replace(/"/g, '\\"').replace(/^\?/, '\\?').replace(/^@/, '\\@').replace(/\n/g, '\\n');
const placeholders = v => (v.match(/%(\d+\$)?[sd]|%%/g) || []).sort().join(',');

function readBase(file) {
  const xml = fs.readFileSync(path.join(RES, 'values', file), 'utf8');
  const entries = [];
  for (const m of xml.matchAll(/<string name="([^"]+)">([\s\S]*?)<\/string>|<plurals name="([^"]+)">([\s\S]*?)<\/plurals>/g)) {
    if (m[1]) entries.push({ kind: 'string', key: m[1], value: unescape(m[2]) });
    else {
      const items = {};
      for (const i of m[4].matchAll(/<item quantity="(\w+)">([\s\S]*?)<\/item>/g)) items[i[1]] = unescape(i[2]);
      entries.push({ kind: 'plurals', key: m[3], items });
    }
  }
  return entries;
}

const langs = process.argv.slice(2).length ? process.argv.slice(2) :
  fs.readdirSync(__dirname).filter(f => /^[a-z]{2}\.js$/.test(f)).map(f => f.slice(0, 2));
let problems = 0;

for (const lang of langs) {
  const dict = require(`./${lang}.js`);
  const used = new Set();
  for (const file of BASE_FILES) {
    const out = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- Generated by tools/i18n/build.js from tools/i18n/${lang}.js -->`, '<resources>'];
    for (const entry of readBase(file)) {
      if (SKIP.has(entry.key)) continue;
      if (entry.kind === 'string') {
        const t = dict.strings[entry.key];
        used.add(entry.key);
        if (t === undefined) { console.log(`${lang}: missing ${entry.key}`); problems++; continue; }
        if (placeholders(t) !== placeholders(entry.value)) { console.log(`${lang}: placeholders differ in ${entry.key}`); problems++; }
        out.push(`    <string name="${entry.key}">${escape(t)}</string>`);
      } else {
        const t = dict.strings[entry.key];
        used.add(entry.key);
        if (!t) { console.log(`${lang}: missing plurals ${entry.key}`); problems++; continue; }
        out.push(`    <plurals name="${entry.key}">`);
        for (const [q, v] of Object.entries(t)) {
          const base = entry.items.other;
          if (placeholders(v).replace('%d', '%1$d') !== placeholders(base).replace('%d', '%1$d') && !(q === 'one' && placeholders(v) === '')) {
            console.log(`${lang}: placeholders differ in ${entry.key}/${q}`); problems++;
          }
          out.push(`        <item quantity="${q}">${escape(v)}</item>`);
        }
        out.push('    </plurals>');
      }
    }
    out.push('</resources>', '');
    fs.mkdirSync(path.join(RES, `values-${lang}`), { recursive: true });
    fs.writeFileSync(path.join(RES, `values-${lang}`, file), out.join('\n'));
  }
  for (const key of Object.keys(dict.strings)) {
    if (!used.has(key) && !SKIP.has(key) && !key.startsWith('type_')) { console.log(`${lang}: unknown key ${key}`); problems++; }
  }
  if (dict.types) {
    const xml = Object.entries(dict.types).map(([k, v]) => `    <string name="type_${k}">${escape(v)}</string>`);
    fs.writeFileSync(path.join(RES, `values-${lang}`, 'types.xml'),
      ['<?xml version="1.0" encoding="utf-8"?>', '<resources>', ...xml, '</resources>', ''].join('\n'));
  }
  if (dict.tips) {
    fs.mkdirSync(path.join(RES, `raw-${lang}`), { recursive: true });
    fs.writeFileSync(path.join(RES, `raw-${lang}`, 'trainer_tips.json'), JSON.stringify({ tips: dict.tips }, null, 2) + '\n');
  }
  console.log(`${lang}: ${used.size} strings, ${dict.tips ? dict.tips.length : 0} tips`);
}
console.log(problems ? `${problems} problems` : 'all good');
process.exitCode = problems ? 1 : 0;
