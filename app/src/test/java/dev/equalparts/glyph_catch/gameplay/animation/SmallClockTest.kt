package dev.equalparts.glyph_catch.gameplay.animation

import org.junit.Assert.assertEquals
import org.junit.Test

class SmallClockTest {
    private fun ascii(frame: IntArray, size: Int) = (0 until size).joinToString("\n") { y ->
        (0 until size).joinToString("") { x -> if (frame[y * size + x] > 0) "#" else "." }
    }

    @Test
    fun `hours on top and minutes below, centered on the 13x13 matrix`() {
        val expected = """
            .............
            ....#..###...
            ...##....#...
            ....#..###...
            ....#..#.....
            ...###.###...
            .............
            ...###.#.#...
            .....#.#.#...
            ...###.###...
            .....#...#...
            ...###...#...
            .............
        """.trimIndent()
        assertEquals(expected, ascii(renderSmallClockFrame("12", "34", 13), 13))
    }

    @Test
    fun `a single-digit hour is centered on its own`() {
        val frame = renderSmallClockFrame("9", "05", 13)
        val row = (0 until 13).joinToString("") { x -> if (frame[13 + x] > 0) "#" else "." }
        assertEquals(".....###.....", row)
    }
}
